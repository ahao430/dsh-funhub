export function parseLevel(rows) {
  const walls = new Set()
  const goals = new Set()
  const boxes = new Set()
  let player = -1
  const h = rows.length
  const w = Math.max(...rows.map((r) => r.length))
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const i = y * w + x
      const c = row[x]
      if (c === '#') walls.add(i)
      if (c === '.' || c === '*' || c === '+') goals.add(i)
      if (c === '$' || c === '*') boxes.add(i)
      if (c === '@' || c === '+') player = i
    }
  })
  return { walls, goals, boxes, player, w, h }
}

/** 走一步：返回 { state, moved, pushed }；不可走（撞墙/推不动）时 moved=false，state 原样。 */
export function sokobanMove(state, dx, dy) {
  const { w } = state
  const from = state.player
  const to = from + dx + dy * w
  if (state.walls.has(to)) return { state, moved: false, pushed: false }
  if (state.boxes.has(to)) {
    const beyond = to + dx + dy * w
    if (state.walls.has(beyond) || state.boxes.has(beyond)) return { state, moved: false, pushed: false }
    const boxes = new Set(state.boxes)
    boxes.delete(to)
    boxes.add(beyond)
    return { state: { ...state, boxes, player: to }, moved: true, pushed: true }
  }
  return { state: { ...state, player: to }, moved: true, pushed: false }
}

export function sokobanCleared(state) {
  for (const b of state.boxes) if (!state.goals.has(b)) return false
  return state.boxes.size > 0
}

